//! Vault-wide reverse indexes derived from authoritative Markdown bytes.
//! No SQL knowledge bodies, secondary writable index or destructive asset GC.
use super::markdown_assets::{asset_root, linked_assets, validate_asset_file};
use super::markdown_cli::{authority_response, knowledge_error};
use super::*;
use serde::Serialize;
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};

#[derive(Debug, Serialize)]
struct NoteReference {
    id: String,
    path: String,
    title: String,
}

#[derive(Debug, Serialize)]
struct AssetAudit {
    referenced: Vec<String>,
    orphaned: Vec<String>,
    missing: Vec<String>,
    corrupt: Vec<String>,
    inspected_notes: usize,
}

fn enumerate_notes(
    host: &orbit_runtime::AuthoritativeHost,
) -> Result<Vec<(NoteReference, String)>, CliError> {
    let mut result = Vec::new();
    for note in host.markdown_knowledge_index().map_err(knowledge_error)? {
        let (_, body) = host
            .markdown_by_id(&note.id)
            .map_err(knowledge_error)?
            .ok_or_else(|| CliError::Usage(format!("indexed note disappeared: {}", note.id)))?;
        result.push((
            NoteReference {
                id: note.id,
                path: note.path,
                title: note.title,
            },
            body,
        ));
    }
    Ok(result)
}

/// Require the exact typed link syntax generated by `note reference`.
/// Partial IDs and arbitrary prose are not interpreted as typed relationships.
pub fn reference_backlinks(
    host: &orbit_runtime::AuthoritativeHost,
    target: &str,
) -> Result<Response, CliError> {
    super::markdown_metadata::validate_typed_target(target)?;
    let token = format!("[{}](orbit://{})", target, target);
    let matches: Vec<_> = enumerate_notes(host)?
        .into_iter()
        .filter_map(|(note, body)| body.contains(&token).then_some(note))
        .collect();
    authority_response(serde_json::json!({"target":target,"backlinks":matches}))
}

pub fn asset_backlinks(
    host: &orbit_runtime::AuthoritativeHost,
    asset: &str,
) -> Result<Response, CliError> {
    if !super::markdown_assets::safe_basename(asset)
        || !super::markdown_assets::is_content_name(asset)
    {
        return Err(CliError::Usage(
            "invalid content-addressed asset name".into(),
        ));
    }
    let matches: Vec<_> = enumerate_notes(host)?
        .into_iter()
        .filter_map(|(note, body)| {
            linked_assets(&body)
                .contains(&asset.to_string())
                .then_some(note)
        })
        .collect();
    authority_response(serde_json::json!({"asset":asset,"backlinks":matches}))
}

/// Report orphaned bytes but never delete them: an interrupted note publication
/// may have left a valid staged blob and external backup may rely on it.
pub fn audit_assets(
    host: &orbit_runtime::AuthoritativeHost,
    db: &Path,
) -> Result<Response, CliError> {
    let notes = enumerate_notes(host)?;
    let mut referenced = BTreeSet::new();
    for (_, body) in &notes {
        referenced.extend(linked_assets(body));
    }
    let root = asset_root(db);
    let mut on_disk = BTreeMap::new();
    if root.exists() {
        let meta = fs::symlink_metadata(&root).map_err(|e| CliError::Io(e.to_string()))?;
        if !meta.is_dir() || meta.file_type().is_symlink() {
            return Err(CliError::Usage("unsafe asset directory".into()));
        }
        for entry in fs::read_dir(&root).map_err(|e| CliError::Io(e.to_string()))? {
            let entry = entry.map_err(|e| CliError::Io(e.to_string()))?;
            let name = entry
                .file_name()
                .into_string()
                .map_err(|_| CliError::Usage("non-UTF8 asset name".into()))?;
            if !super::markdown_assets::is_content_name(&name) {
                return Err(CliError::Usage(format!("unexpected asset entry: {name}")));
            }
            let ty = entry.file_type().map_err(|e| CliError::Io(e.to_string()))?;
            if !ty.is_file() || ty.is_symlink() {
                return Err(CliError::Usage(format!("unsafe asset entry: {name}")));
            }
            on_disk.insert(name, entry.path());
        }
    }
    let mut missing = Vec::new();
    let mut corrupt = Vec::new();
    for name in &referenced {
        match on_disk.get(name) {
            None => missing.push(name.clone()),
            Some(path) => match validate_asset_file(path) {
                Ok(bytes) => {
                    let digest = format!("{:x}", Sha256::digest(&bytes));
                    if !name.starts_with(&digest) {
                        corrupt.push(name.clone());
                    }
                }
                Err(_) => corrupt.push(name.clone()),
            },
        }
    }
    let orphaned = on_disk
        .keys()
        .filter(|name| !referenced.contains(*name))
        .cloned()
        .collect();
    authority_response(AssetAudit {
        referenced: referenced.into_iter().collect(),
        orphaned,
        missing,
        corrupt,
        inspected_notes: notes.len(),
    })
}

#[cfg(test)]
mod tests {
    #[test]
    fn exact_typed_reference_token_is_not_prefix_match() {
        let body = "[project:abc2](orbit://project:abc2)";
        assert!(!body.contains("[project:abc](orbit://project:abc)"));
    }
    #[test]
    fn audit_is_read_only_by_construction() {
        assert!(super::markdown_assets::is_content_name(&format!(
            "{}.png",
            "a".repeat(64)
        )));
        assert!(!super::markdown_assets::is_content_name("something.png"));
    }
}
